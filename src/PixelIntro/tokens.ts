/** 小图标：金币（6×6）与心（7×6） */
export const ICONS: Record<"coin" | "heart", { w: number; h: number; rows: string[] }> = {
  // 实心圆，不要做空心环 —— 6×6 的空心环会被读成版权符号 ©（页脚正好也有一个 ©）
  coin: { w: 6, h: 6, rows: [".####.", "######", "######", "######", "######", ".####."] },
  heart: {
    w: 7,
    h: 6,
    rows: [".##.##.", "#######", "#######", ".#####.", "..###..", "...#..."],
  },
};

/**
 * 排版宽度：n 个字模，字间留 `tracking` 个虚拟像素。
 * 末字后面那点间距不算，所以是 `n*(W+tracking) - tracking`。
 */
export const textWidth = (text: string, scale: number, tracking = 1) =>
  (text.length * (GLYPH_W + tracking) - tracking) * scale;

/** 确定性伪随机。Remotion 逐帧可能落在不同进程上，`Math.random()` 会让同一帧每次不同 */
export const rnd = (n: number) => {
  const v = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return v - Math.floor(v);
};

/** 把点阵字模展开成一组 box-shadow —— 一个 div 就能画完整行字，不用几百个节点 */
export const glyphShadows = (
  text: string,
  scale: number,
  color: string,
  tracking = 1,
): string => {
  const out: string[] = [];
  let gx = 0;
  for (const raw of text.toUpperCase()) {
    const rows = GLYPHS[raw];
    if (rows) {
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          if (rows[r][c] === "#") {
            out.push(`${(gx + c) * scale}px ${r * scale}px 0 0 ${color}`);
          }
        }
      }
    }
    gx += GLYPH_W + tracking;
  }
  return out.join(", ");
};

/** 同上，画一个小图标 */
export const iconShadows = (
  key: "coin" | "heart",
  scale: number,
  color: string,
): string => {
  const { w, h, rows } = ICONS[key];
  const out: string[] = [];
  for (let r = 0; r < h; r++) {
    for (let c = 0; c < w; c++) {
      if (rows[r][c] === "#") out.push(`${c * scale}px ${r * scale}px 0 0 ${color}`);
    }
  }
  return out.join(", ");
};
